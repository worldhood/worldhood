// Reproducible reference authoring: existing OSM pavement geometry, not a traced photograph.
import fs from 'node:fs';
import {gunzipSync} from 'node:zlib';
import proj4 from 'proj4';
const reg=JSON.parse(fs.readFileSync('public/cities/index.json')),city=reg.cities.find(c=>c.id==='oulu');
const data=JSON.parse(gunzipSync(fs.readFileSync('public/cities/oulu/city.pack')));
const convert=proj4('EPSG:4326',city.projection);
const local=(lon,lat)=>{const [x,y]=convert.forward([+lon,+lat]);return [x,-y];};
const statueXml=fs.readFileSync('data/raw/cities/oulu/node-576296537.osm','utf8');
const statue=local(statueXml.match(/lon="([^"]+)"/)[1],statueXml.match(/lat="([^"]+)"/)[1]);
const squareXml=fs.readFileSync('data/raw/cities/oulu/way-27690320-full.osm','utf8');
const nodes=new Map([...squareXml.matchAll(/<node\s+id="(\d+)"[^>]*lat="([^"]+)" lon="([^"]+)"/g)].map(m=>[m[1],local(m[3],m[2])]));
const square=[...squareXml.matchAll(/<nd ref="(\d+)"/g)].map(m=>nodes.get(m[1]));
if(square.some(p=>!p))throw Error('Incomplete OSM square geometry');
const old=JSON.parse(fs.readFileSync('cities/oulu/market-reference.json'));
const pavement=data.pavement.filter(p=>['osm-way-6009035','osm-way-27541283','osm-way-56648009','osm-way-239062257'].includes(p.id));
const ref={...old,referenceOnly:false,adapter:'authored-osm',centreLocal:[-282,-143],radiusMetres:150,hallBuilding:'osm-way-28979742',source:'OpenStreetMap contributors (ODbL); Estormiz CC0 photographs; original photographs by zaw-ye-tun used with permission. No photo textures distributed.',model:{...old.model,statue,statueYaw:2.15,source:'Statue location: OSM node 576296537; height 2.20 m excluding plinth: OSM and MunOulu 2026-06-05. Hall dimensions and architectural details: photo estimates; footprint: OSM.'},paving:[{kind:'grey-pavers',rings:[square]},...pavement.map(p=>({kind:p.id==='osm-way-6009035'?'setts':'grey-pavers',rings:p.rings}))]};
fs.writeFileSync('cities/oulu/market-reference.json',JSON.stringify(ref,null,1));
ref.houseBuilding='osm-way-94507906';
ref.model.statueYaw=-2.13;
ref.model.trees=[{u:-14,v:20,height:7,bare:true},{u:4,v:20,height:7,bare:true},{p:[-232,-163],height:5.5,bare:false}];
ref.model.signs=[{u:21,v:20,kind:'no-parking'},{u:-21,v:22,kind:'parking'}];
ref.paving=ref.paving.map(p=>({...p,kind:p.kind==='grey-pavers'?'market-pavers':p.kind}));
const mapXml=fs.readFileSync('data/raw/cities/oulu/market-map.osm','utf8');
const mapNodes=new Map([...mapXml.matchAll(/<node\s+id="(\d+)"[^>]*lat="([^"]+)" lon="([^"]+)"/g)].map(m=>[m[1],local(m[3],m[2])]));
const plazaWay=mapXml.match(/<way id="50118176"[^]*?<\/way>/)[0];
const plaza=[...plazaWay.matchAll(/<nd ref="(\d+)"/g)].map(m=>mapNodes.get(m[1]));
if(plaza.some(p=>!p))throw Error('Incomplete OSM market plaza geometry');
ref.paving.unshift({kind:'market-pavers',rings:[plaza]});
const [sx,sz]=statue;ref.paving.push({kind:'rose-fans',rings:[[[sx-2,sz-2],[sx+2,sz-2],[sx+2,sz+2],[sx-2,sz+2],[sx-2,sz-2]]]});
fs.writeFileSync('cities/oulu/market-reference.json',JSON.stringify(ref,null,1));
const facades=JSON.parse(fs.readFileSync('cities/oulu/facades.json'));
facades.buildings['osm-way-94507906']={appearanceOnly:true,wall:'#c89192',material:'timber',evidence:{photos:[{id:'own_41645f59d53e',captured:'2025-06-24'}],confidence:.7,source:'own-photo-sources.json',scope:'Pink visible facade only; window rhythm, roof geometry and heights remain provisional.'}};
fs.writeFileSync('cities/oulu/facades.json',JSON.stringify(facades,null,1));
console.log({paving:ref.paving.length,statue:ref.model.statue});
